CREATE TABLE MYST_COUNTRY_BOUNDARIES (
    FIPS_CNTRY VARCHAR2(2),
    CNTRY_NAME VARCHAR2(40),
    STGEOM ST_MULTIPOLYGON
);

-- zad. 3B
--SELECT * FROM COUNTRY_BOUNDARIES;

INSERT INTO MYST_COUNTRY_BOUNDARIES (FIPS_CNTRY, CNTRY_NAME, STGEOM)
SELECT cb.FIPS_CNTRY, cb.CNTRY_NAME, ST_MULTIPOLYGON(cb.GEOM)
FROM ztpd.COUNTRY_BOUNDARIES cb;
COMMIT;

-- zad. 3C
SELECT b.stgeom.st_geometrytype() AS typ_obiektu, COUNT(*) AS ile
FROM MYST_COUNTRY_BOUNDARIES b
GROUP BY b.stgeom.st_geometrytype()
ORDER BY ile DESC;

-- zad. 3D
SELECT b.stgeom.st_issimple()
FROM MYST_COUNTRY_BOUNDARIES b;

-- zad. 4A
SELECT cb.CNTRY_NAME, COUNT(mc.CITY_NAME)
FROM MYST_COUNTRY_BOUNDARIES cb
JOIN MYST_MAJOR_CITIES mc ON cb.stgeom.st_contains(mc.STGEOM) = 1
GROUP BY cb.CNTRY_NAME;

-- zad. 4B
SELECT a.CNTRY_NAME AS A_NAME,
       b.CNTRY_NAME AS B_NAME
FROM MYST_COUNTRY_BOUNDARIES a
JOIN MYST_COUNTRY_BOUNDARIES b
  ON a.stgeom.st_touches(b.STGEOM) = 1
WHERE b.CNTRY_NAME = 'Czech Republic';

-- zad. 4C
SELECT DISTINCT cb.CNTRY_NAME, r.name
FROM MYST_COUNTRY_BOUNDARIES cb
JOIN ztpd.RIVERS r
  ON cb.stgeom.st_crosses(ST_LINESTRING(r.geom)) = 1
WHERE cb.CNTRY_NAME = 'Czech Republic';

-- zad. 4D
SELECT TREAT(a.stgeom.st_union(b.STGEOM) AS ST_POLYGON).st_area() POWIERZCHNIA
FROM MYST_COUNTRY_BOUNDARIES a, MYST_COUNTRY_BOUNDARIES b
WHERE b.CNTRY_NAME = 'Czech Republic' 
AND a.CNTRY_NAME = 'Slovakia';

-- zad. 4E
SELECT h.stgeom.st_difference(ST_GEOMETRY(w.geom)) AS obiekt, h.stgeom.st_difference(ST_GEOMETRY(w.geom)).st_geometrytype() AS wegry_bez
FROM MYST_COUNTRY_BOUNDARIES h
CROSS JOIN ztpd.WATER_BODIES w
WHERE h.CNTRY_NAME = 'Hungary'
AND w.name = 'Balaton';


